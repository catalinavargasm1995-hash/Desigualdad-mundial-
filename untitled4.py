#Conectar pagina web con la api del Banco Mundial

import requests
import pandas as pd

BASE_URL = "https://api.worldbank.org/v2"

def get_indicator(
    indicator,
    country="all",
    start_year=2000,
    end_year=2025
):
    url = (
        f"{BASE_URL}/country/{country}/indicator/"
        f"{indicator}"
    )

    params = {
        "format": "json",
        "date": f"{start_year}:{end_year}",
        "per_page": 20000
    }

    response = requests.get(
        url,
        params=params,
        timeout=30
    )

    response.raise_for_status()

    result = response.json()

    if not isinstance(result, list) or len(result) < 2:
        return pd.DataFrame()

    records = result[1]

    if not records:
        return pd.DataFrame()

    data = []

    for item in records:
        if item["value"] is not None:
            data.append({
                "country": item["country"]["value"],
                "country_code": item["countryiso3code"],
                "year": int(item["date"]),
                "value": float(item["value"])
            })

    return pd.DataFrame(data)

df = get_indicator(
    indicator="SI.POV.GINI",
    country="COL",
    start_year=2000,
    end_year=2025
)

display(df.head(10))

